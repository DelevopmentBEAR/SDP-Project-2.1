# Imports os to hold the API key in environment variables
import os
# Imports the genai module from the google package to access the Gemini API
from google import genai
# Imports the types module from the google.genai package to define the configuration for generating content
from google.genai import types
# Imports sys to handle system exit in case of missing system instruction
import sys

# Retrieves the Gemini API key from the environment variables
api_key = os.environ.get("GEMINI_API_KEY")
# Checks if the API key is not set, and raises a SystemExit with a message if it's missing
if not api_key:
    raise SystemExit("Set the GEMINI_API_KEY environment variable first.")

# Creates a client instance of the Gemini API using the provided API key
client = genai.Client(api_key=api_key)

# Attempts to read the system instruction from a text file, and exits the program if the file is missing
try:
    with open('chat_system_instruction.txt', 'r') as f:
        system_instruction_text = f.read()
except:
    print("Missing system instruction, quiting program")
    sys.exit()

# Defines a function to get a chat response from the Gemini API based on the user's question
def get_chat_response(question: str) -> str:
    # Generates a response from the Gemini API using the specified model and system instruction
    response = client.models.generate_content(
        model="gemini-3.1-flash-lite",
        contents=question,
        config=types.GenerateContentConfig(
            system_instruction=system_instruction_text
        )
    )
    # Returns the text of the response generated by the Gemini API
    return response.text

# If the script is run directly, it enters a loop to continuously prompt the user for input and print the chat response
if __name__ == "__main__":
    while True:
        # Prompts the user for a question and retrieves the chat response using the get_chat_response function
        question = input("> ")
        print(get_chat_response(question))